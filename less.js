/* 
  =============================================================================
  📖 МИНИ-ЛЕКЦИЯ: НОВАЯ КОМАНДА — confirm()
  =============================================================================
  До этого момента вы знали две команды для общения с пользователем:
  1. alert("Текст") — просто выводит сообщение на экран (есть только кнопка «ОК»).
  2. prompt("Вопрос") — запрашивает у пользователя строку ТЕКСТА.
  
  Сегодня мы познакомимся с функцией confirm("Вопрос"). 
  Она нужна, когда от пользователя требуется четкий ответ: «ДА» или «НЕТ».
  
  Как она работает:
  Браузер показывает окно с вопросом и ДВУМЯ кнопками: «ОК» и «Отмена».
  Функция возвращает логическое значение (Boolean):
  - Если пользователь нажал «ОК» (Да) ➔ возвращается значение true.
  - Если пользователь нажал «Отмена» (Нет) ➔ возвращается значение false.
  
  Пример использования в коде:
  ---------------------------------------------------------------------------
  const wantsCookies = confirm("Вы любите печенье?");
  
  if (wantsCookies === true) {
      alert("Вот ваша печенька! 🍪");
  } else {
      alert("Жаль, тогда держите яблоко! 🍏");
  }
  ---------------------------------------------------------------------------
  ⚡ Подсказка: Условие if (wantsCookies === true) можно записать короче, 
  так как переменная уже хранит true или false: if (wantsCookies) { ... }
*/

